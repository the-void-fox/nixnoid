parse_git_branch() {
  git branch 2>/dev/null | grep '\*' | sed 's/* / /'
}
PS1='\[\e[38;5;212m\]≽^•⩊•^≼\[\e[0m\] \[\e[38;5;117m\]\w\[\e[38;5;156m\]$(parse_git_branch)\[\e[0m\] ❯ '

__theme_not_found() {
  local cmd="$1"
  local reactions=(
    "Ня?! '$cmd' — это что за покемон? ≽^•⩊•^≼"
    "Хм-м... '$cmd'? Такого заклинания я не знаю, ня~"
    "'$cmd'? *тыкает лапкой* Оно не работает, ня!"
    "Ошибка-ня! '$cmd' не найдена в этой вселенной~"
    "'$cmd'... Ты уверен что это существует? (◕ᴗ◕✿)"
    "Ня-а-а?! '$cmd' сбежала куда-то... ≽^•⩊•^≼"
    "*смущённо* '$cmd' не в моём словаре, ня~"
  )
  local index=$((RANDOM % ${#reactions[@]}))
  echo ""
  echo -e "\e[38;5;212m╭──────────────────────────────────────────\e[0m"
  echo -e "\e[38;5;212m│\e[0m  \e[38;5;203m✗\e[0m \e[38;5;117m${reactions[$index]}\e[0m"
  echo -e "\e[38;5;212m│\e[0m"
  echo -e "\e[38;5;212m│\e[0m  \e[38;5;248m Попробуй:\e[0m"
  echo -e "\e[38;5;212m│\e[0m     \e[38;5;156m• nix-shell -p $cmd\e[0m \e[38;5;243m(временно)\e[0m"
  echo -e "\e[38;5;212m│\e[0m     \e[38;5;156m• nix search nixpkgs#$cmd\e[0m \e[38;5;243m(поиск)\e[0m"
